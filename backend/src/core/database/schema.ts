import {
  pgTable,
  uuid,
  varchar,
  text,
  timestamp,
  pgEnum,
  index,
  uniqueIndex,
} from 'drizzle-orm/pg-core';
import { relations } from 'drizzle-orm';

/* ──────────────────────────────────────────────────────────
 * Enums
 * ────────────────────────────────────────────────────────── */

export const moodLevelEnum = pgEnum('mood_level', [
  'awful',
  'bad',
  'okay',
  'good',
  'great',
]);

export const audioCategoryEnum = pgEnum('audio_category', [
  'relaxing',
  'workout',
]);

export const chatRoleEnum = pgEnum('chat_role', ['user', 'ai']);

/* ──────────────────────────────────────────────────────────
 * Users
 *
 * User identity is unified with Neon Auth (Better Auth).
 * The primary key `id` is the text ID generated by Neon Auth,
 * eliminating the previous dual-identity and extra translation query.
 * ────────────────────────────────────────────────────────── */

export const users = pgTable(
  'users',
  {
    id: text('id').primaryKey(),
    email: varchar('email', { length: 255 }).notNull().unique(),
    name: varchar('name', { length: 255 }),
    avatarUrl: text('avatar_url'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    uniqueIndex('idx_users_email').on(table.email),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Mood Entries
 *
 * Enforces one mood entry per user per calendar day (entryDate: YYYY-MM-DD)
 * at the database constraint level, preventing duplicate insert races.
 * ────────────────────────────────────────────────────────── */

export const moodEntries = pgTable(
  'mood_entries',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    mood: moodLevelEnum('mood').notNull(),
    note: text('note'),
    entryDate: varchar('entry_date', { length: 10 }).notNull(),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    uniqueIndex('idx_mood_entries_user_date').on(table.userId, table.entryDate),
    index('idx_mood_entries_user_created').on(table.userId, table.createdAt),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Journal Entries
 * ────────────────────────────────────────────────────────── */

export const journalEntries = pgTable(
  'journal_entries',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    title: varchar('title', { length: 500 }).notNull(),
    content: text('content').notNull(),
    detectedMood: moodLevelEnum('detected_mood'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index('idx_journal_entries_user_created').on(table.userId, table.createdAt),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Audio Tracks
 * ────────────────────────────────────────────────────────── */

export const audioTracks = pgTable(
  'audio_tracks',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    title: varchar('title', { length: 500 }).notNull(),
    author: varchar('author', { length: 255 }),
    duration: varchar('duration', { length: 20 }).notNull(),
    category: audioCategoryEnum('category').notNull(),
    audioUrl: text('audio_url').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index('idx_audio_tracks_category').on(table.category),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Daily Quotes
 * ────────────────────────────────────────────────────────── */

export const dailyQuotes = pgTable(
  'daily_quotes',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    quoteText: text('quote_text').notNull(),
    author: varchar('author', { length: 255 }),
    date: timestamp('date', { withTimezone: true }).notNull(),
  },
  (table) => [
    index('idx_daily_quotes_date').on(table.date),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Chat Messages
 * ────────────────────────────────────────────────────────── */

export const chatMessages = pgTable(
  'chat_messages',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    content: text('content').notNull(),
    role: chatRoleEnum('role').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index('idx_chat_messages_user_created').on(table.userId, table.createdAt),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Push Tokens
 * ────────────────────────────────────────────────────────── */

export const pushTokens = pgTable(
  'push_tokens',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    token: varchar('token', { length: 255 }).notNull().unique(),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index('idx_push_tokens_user').on(table.userId),
  ],
);

/* ──────────────────────────────────────────────────────────
 * Drizzle Relations
 * ────────────────────────────────────────────────────────── */

export const usersRelations = relations(users, ({ many }) => ({
  moodEntries: many(moodEntries),
  journalEntries: many(journalEntries),
  chatMessages: many(chatMessages),
  pushTokens: many(pushTokens),
}));

export const moodEntriesRelations = relations(moodEntries, ({ one }) => ({
  user: one(users, {
    fields: [moodEntries.userId],
    references: [users.id],
  }),
}));

export const journalEntriesRelations = relations(journalEntries, ({ one }) => ({
  user: one(users, {
    fields: [journalEntries.userId],
    references: [users.id],
  }),
}));

export const chatMessagesRelations = relations(chatMessages, ({ one }) => ({
  user: one(users, {
    fields: [chatMessages.userId],
    references: [users.id],
  }),
}));

export const pushTokensRelations = relations(pushTokens, ({ one }) => ({
  user: one(users, {
    fields: [pushTokens.userId],
    references: [users.id],
  }),
}));
